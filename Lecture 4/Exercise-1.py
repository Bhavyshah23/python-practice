# Basic Dictionary

student ={
    "name" : "Bhavy Shah",
    "age" : 20,
    "marks" : 87.5,
    "subjects": ["Maths", "Science", "English"]
}
# Print the entire dictionary
print(student)

# Print only the student's name
print(student["name"])

# Print only the list of subjects
print(student["subjects"])